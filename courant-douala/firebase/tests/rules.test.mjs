import { initializeTestEnvironment, assertSucceeds, assertFails } from '@firebase/rules-unit-testing';
import { readFileSync } from 'fs';
import { doc, getDoc, setDoc, deleteDoc, runTransaction } from 'firebase/firestore';
const env = await initializeTestEnvironment({ projectId: 'demo-courant', firestore: { rules: readFileSync(new URL('../firestore.rules', import.meta.url),'utf8'), host:'127.0.0.1', port: 8085 } });
const user = env.authenticatedContext('anon1').firestore();
const anon = env.unauthenticatedContext().firestore();
const e = { on:false, since:1, last:1, n:1, h:[{on:false,t:1}] };
const ok = [], ko = [];
const t = async (name, p, expect) => { try { await (expect ? assertSucceeds(p) : assertFails(p)); ok.push(name);} catch(err){ ko.push(name+': '+err.message);} };
await t('read public', getDoc(doc(anon,'shards/0')), true);
await t('unauth write denied', setDoc(doc(anon,'shards/0'),{q:{akwa:{p:e}}},{merge:true}), false);
await t('create shard', setDoc(doc(user,'shards/0'),{q:{akwa:{p:e}}},{merge:true}), true);
await t('add other quartier', setDoc(doc(user,'shards/0'),{q:{bali:{w:e}}},{merge:true}), true);
await t('update existing quartier', setDoc(doc(user,'shards/0'),{q:{akwa:{p:{...e,n:2}}}},{merge:true}), true);
await t('app transaction', runTransaction(user, async tx => { await tx.get(doc(user,'shards/0')); tx.set(doc(user,'shards/0'),{q:{akwa:{w:e}}},{merge:true}); }), true);
await t('two quartiers at once denied', setDoc(doc(user,'shards/0'),{q:{akwa:{p:e},bali:{p:e}}},{merge:true}), false);
await t('wipe denied', setDoc(doc(user,'shards/0'),{q:{}}), false);
await t('extra field denied', setDoc(doc(user,'shards/0'),{x:1},{merge:true}), false);
await t('bad shard denied', setDoc(doc(user,'shards/9'),{q:{akwa:{p:e}}}), false);
await t('delete denied', deleteDoc(doc(user,'shards/0')), false);
await t('other collection denied', setDoc(doc(user,'foo/bar'),{a:1}), false);
console.log('PASS', ok.length, ok.join(', ')); console.log('FAIL', ko.length, ko.join('\n'));
await env.cleanup(); process.exit(ko.length?1:0);
